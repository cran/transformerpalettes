#' transformerpalettes: Color Palettes Inspired by Transformers Toys, Cartoons and Comics
#'
#' Color palettes drawn from the Transformers franchise, centered on the
#' Generation 1 toys and extending to their Generation 2 re-releases, the
#' cartoon animation models and the Marvel comics, plus ggplot2 color and
#' fill scales.
#'
#' Start with [tf_palette()] to pull colors from a character,
#' [tf_palette_names()] to list the available characters,
#' [tf_team_palette()] for one color per member of a combiner team, and
#' [scale_colour_tf()] / [scale_fill_tf()] to use them in ggplot2. Run
#' [tf_show_palettes()] to see the palettes at once and [tf_find_palettes()]
#' to shortlist the ones that suit a kind of plot.
#'
#' Hex values are approximations curated from product photography on the
#' Transformers Wiki. transformerpalettes is a fan project and is not affiliated with
#' or endorsed by Hasbro or Takara Tomy.
#'
